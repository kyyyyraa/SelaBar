/// Returns `(badge_label, hex_color)` for DeskNotch's file-shelf extension icons (`PDF`, `DOC`, `XLS`, etc.).
pub fn file_badge_style(ext: &str, is_dir: bool) -> (&'static str, &'static str) {
    if is_dir {
        return ("DIR", "#F59E0B");
    }
    match ext.to_ascii_lowercase().trim_start_matches('.') {
        "pdf" => ("PDF", "#EF4444"),
        "doc" | "docx" | "rtf" | "odt" => ("DOC", "#3B82F6"),
        "xls" | "xlsx" | "csv" | "ods" => ("XLS", "#22C55E"),
        "ppt" | "pptx" | "odp" => ("PPT", "#F97316"),
        "zip" | "rar" | "7z" | "tar" | "gz" => ("ZIP", "#EAB308"),
        "mp3" | "wav" | "flac" | "aac" | "ogg" | "m4a" => ("AUD", "#EC4899"),
        "mp4" | "mkv" | "mov" | "avi" | "webm" => ("VID", "#6366F1"),
        "rs" | "ts" | "tsx" | "js" | "jsx" | "py" | "json" | "toml" | "html" | "css" | "md"
        | "c" | "cpp" | "h" | "go" => ("CODE", "#A855F7"),
        "exe" | "msi" | "bat" | "cmd" | "ps1" => ("APP", "#14B8A6"),
        "png" | "jpg" | "jpeg" | "gif" | "webp" | "bmp" | "ico" | "svg" => ("IMG", "#38BDF8"),
        _ => ("FILE", "#94A3B8"),
    }
}
